"""
AAS Client (Event-Driven Bridge from OPC UA to BaSyx)

What this program does (in simple terms):
- It connects to a machine's OPC UA server.
- It listens for specific machine/job events.
- When a matching event arrives, it extracts relevant job information.
- It sends that information to create/update an Asset Administration Shell (AAS)
    representation via the BaSyx APIs.

Why this is useful:
- OPC UA is used by machines to expose data and events.
- AAS is a standardized digital representation of an asset (for example, a machine
    or a job) so IT systems can consume it consistently.
- This script acts as a translator/bridge: machine events in, AAS updates out.

High-level flow:
1) Connect to OPC UA (`UA_ENDPOINT_URL`), retrying while the server is unavailable.
2) Resolve namespaces and navigate to the machine's `JobOrderResults` node.
3) Find the event type generated by that node.
4) Subscribe to those events (server-side filtered).
5) Put incoming events into a bounded async queue.
6) Process queued events and map fields into `job_data`.
7) Call `create_aas_for_job(...)` to publish/update AAS data in BaSyx.

Robustness:
- One shared `AsyncBaSyxClient` is reused for all registrations.
- A single failing event is logged and skipped instead of ending the process.
- The event queue is bounded; when it is full the oldest event is dropped (and the
    number of dropped events is reported).
- SIGINT/SIGTERM (where supported) end the processing loop, then the OPC UA client
    and the BaSyx client are closed.

Configuration:
- All runtime settings (server URLs, node id, timing) come from `config.py`
    and can be overridden through environment variables.
"""

import asyncio
import signal
import sys
from typing import Optional

from asyncua import Client, Node, ua
from asyncua.common.events import Event
from basyx_utils.client import AsyncBaSyxClient
from common.helper import make_nodeid_string, variant_to_json_serializable
from config import (
    EVENT_QUEUE_MAXSIZE,
    UA_CONNECT_MAX_ATTEMPTS,
    UA_CONNECT_RETRY_BASE_DELAY,
    UA_ENDPOINT_URL,
    UA_MACHINE_INSTANCE_NODEID,
    UA_PUBLISHING_INTERVAL,
    UA_RECONNECT_MAX_DELAY,
    UA_REQUEST_TIMEOUT,
)
from ua_job_aas import create_aas_for_job
from ua_machine_aas import create_aas_for_identification

EXIT_CODE_OK = 0
EXIT_CODE_ERROR = 1
EXIT_CODE_INTERRUPTED = 130


class SubscriptionHandler:
    """
    The SubscriptionHandler is used to handle the data that is received for the subscription.

    Queue handling: events are never awaited into the queue, because asyncua calls the
    callbacks from separate tasks. A blocking put would pile up tasks when BaSyx is slow,
    so a full queue drops the oldest event instead.
    """

    def __init__(self) -> None:
        self.event_queue: asyncio.Queue[Event] = asyncio.Queue(EVENT_QUEUE_MAXSIZE)
        self.dropped_events: int = 0

    async def event_notification(self, event: Event):
        """
        Callback for asyncua Subscription.
        This method will be called when the Client received an event message from the Server.
        """
        self._enqueue_event(event)

    def _enqueue_event(self, event: Event) -> None:
        """Queue an event without blocking the callback, dropping the oldest one when full."""
        if self.event_queue.full():
            try:
                self.event_queue.get_nowait()
            except asyncio.QueueEmpty:
                pass
            self.dropped_events += 1
            print(
                f"Event queue full ({EVENT_QUEUE_MAXSIZE} events), dropped the oldest event "
                f"(total dropped events: {self.dropped_events})"
            )
        try:
            self.event_queue.put_nowait(event)
        except asyncio.QueueFull:
            self.dropped_events += 1
            print(
                f"Event queue full ({EVENT_QUEUE_MAXSIZE} events), dropped the incoming event "
                f"(total dropped events: {self.dropped_events})"
            )

    async def datachange_notification(self, node: Node, val, data):
        """
        Callback for asyncua Subscription.
        This method will be called when the Client received a data change message from the Server.
        We use this to detect if the subscription is still alive, as some OPC UA
        Servers may silently drop subscriptions after some time.
        """
        # print(f"DataChange Notification - Node: {node}, Value: {val}, Data: {data}")

    async def status_change_notification(self, status):
        """
        Callback for asyncua Subscription.
        This method will be called when the Client received a status change message from the Server.
        We can use this to detect if the subscription is still alive or if there are any issues with the connection.
        """
        print(f"Subscription Status Change: {status}")


async def process_event(
    event: Event,
    eventtype_nodeid: Optional[str] = None,
    eventtype_displayname: Optional[str] = None,
    basyx_client: Optional[AsyncBaSyxClient] = None,
) -> None:
    """Process one queued OPC UA event and forward matching JobOrder events to AAS creation."""
    if event is None:
        return
    # Keep this check even with server-side filtering as a defensive guard
    # against misconfigured filters or server-side model changes.
    if event.EventType.to_string() == eventtype_nodeid:
        print(f"Received new Event of type: {eventtype_displayname} [{event.EventType.to_string()}] processing...")
        await create_aas_for_job(event.get_event_props_as_fields_dict(), basyx_client)
        return

    print(f"Received other event type, ignoring... EventType: {event.EventType.to_string()}")


async def _connect_ua_client(client: Client) -> bool:
    """
    Connect to the OPC UA server, retrying with exponential backoff.

    Returns True on success, or False when UA_CONNECT_MAX_ATTEMPTS is exhausted.
    """
    attempt = 0
    while True:
        attempt += 1
        try:
            await client.connect(auto_reconnect=True, reconnect_max_delay=UA_RECONNECT_MAX_DELAY)
            return True
        except Exception as ex:  # pylint: disable=broad-except
            print(f"Could not connect to OPC UA server {UA_ENDPOINT_URL} (attempt {attempt}): {ex!r}")
            if 0 < UA_CONNECT_MAX_ATTEMPTS <= attempt:
                print(f"Giving up after {attempt} connection attempts")
                return False
            delay = min(UA_CONNECT_RETRY_BASE_DELAY * (2 ** (attempt - 1)), UA_RECONNECT_MAX_DELAY)
            print(f"Retrying connection in {delay} seconds...")
            await asyncio.sleep(delay)


def _find_namespace_index(namespace_array: list[str], namespace_uri: str) -> Optional[int]:
    """Return the index of a namespace, or None when the server does not advertise it."""
    try:
        return namespace_array.index(namespace_uri)
    except ValueError:
        print(f"Namespace {namespace_uri!r} not found in namespace array: {namespace_array}")
        return None


def _install_signal_handlers(stop_event: asyncio.Event) -> bool:
    """
    Install SIGINT/SIGTERM handlers that request a graceful shutdown.

    Returns False on platforms without signal-handler support (Windows), where the
    KeyboardInterrupt path in `main()` is used instead.
    """
    loop = asyncio.get_running_loop()
    supported = False
    for signal_name in ("SIGINT", "SIGTERM"):
        signal_number = getattr(signal, signal_name, None)
        if signal_number is None:
            continue
        try:
            loop.add_signal_handler(signal_number, stop_event.set)
            supported = True
        except (NotImplementedError, RuntimeError):
            continue
    return supported


async def _read_machine_identification(machine_node: Node, di_index: int) -> dict:
    """Read the identification properties of the machine instance."""
    identification_node: Node = await machine_node.get_child(f"{di_index}:Identification")
    identification_properties = await identification_node.get_properties()
    identification = {}
    for prop in identification_properties:
        prop_name = await prop.read_display_name()
        prop_value: ua.DataValue = await prop.read_data_value()
        identification[prop_name.Text] = variant_to_json_serializable(prop_value.Value)
    return identification


async def _find_job_management_node(
    machine_node: Node, machinery_index: int, machinery_jobs_index: int
) -> Optional[Node]:
    """Locate the JobManagement building block of the machine instance."""
    building_blocks_node: Node = await machine_node.get_child(f"{machinery_index}:MachineryBuildingBlocks")
    print(f"Found OPC for Machinery BuildingBlocks node: {await building_blocks_node.read_display_name()}")

    try:
        job_manager_node: Node = await building_blocks_node.get_child(
            f"{machine_node.nodeid.NamespaceIndex}:JobManagement"
        )
        print(f"Found OPC for Machinery JobManagement node: {await job_manager_node.read_display_name()}")
        return job_manager_node
    except ua.UaError as ex:
        print(f"Error finding JobManagement node in Machinery BuildingBlocks: {ex}")

    # OPC for Machinery: DefaultInstanceBrowseName
    try:
        job_manager_node = await building_blocks_node.get_child(f"{machinery_jobs_index}:JobManagement")
    except ua.UaError as ex:
        print(f"Error finding JobManagement node by DefaultInstanceBrowseName: {ex}")
        return None
    print(
        "Found OPC for Machinery JobManagement node with "
        f"DefaultInstanceBrowseName: {await job_manager_node.read_display_name()}"
    )
    return job_manager_node


async def _run_event_loop(
    handler: SubscriptionHandler,
    basyx_client: AsyncBaSyxClient,
    event_type_nodeid: str,
    event_type_displayname: str,
    stop_event: asyncio.Event,
) -> int:
    """Consume the event queue until shutdown is requested and return the exit code."""
    # Polling keeps the loop simple; when idle, wake-up cadence follows the
    # configured publishing interval. Every event is processed under its own
    # try/except so a single bad event cannot end the process.
    idle_timeout = UA_PUBLISHING_INTERVAL / 1000
    while not stop_event.is_set():
        try:
            event = await asyncio.wait_for(handler.event_queue.get(), timeout=idle_timeout)
        except asyncio.TimeoutError:
            continue
        try:
            await process_event(event, event_type_nodeid, event_type_displayname, basyx_client)
        except Exception as ex:  # pylint: disable=broad-except
            print(f"Error while processing an event, continuing with the next one: {ex!r}")

    if handler.dropped_events:
        print(f"Shutdown: {handler.dropped_events} event(s) were dropped because the queue was full")
    return EXIT_CODE_OK


async def main() -> int:  # pylint: disable=too-many-statements
    """Connect to OPC UA, subscribe to events, and continuously process event queue entries."""
    stop_event = asyncio.Event()
    _install_signal_handlers(stop_event)

    handler = SubscriptionHandler()
    client = Client(url=UA_ENDPOINT_URL, timeout=UA_REQUEST_TIMEOUT)
    client.application_uri = "urn:ua4machinery2aas-client"
    # One client instance for the whole process: it keeps the HTTP connections warm.
    basyx_client = AsyncBaSyxClient()
    exit_code = EXIT_CODE_ERROR
    try:
        if not await _connect_ua_client(client):
            return EXIT_CODE_ERROR
        print(f"Connected to OPC UA Server at {UA_ENDPOINT_URL}")

        # Load custom structure/type metadata so event payload fields can be
        # deserialized into typed Python objects instead of opaque Variants.
        await client.load_data_type_definitions()  # OPC UA v1.04 Structures
        await client.load_type_definitions()  # OPC UA v1.03 Structures

        namespace_array = await client.get_namespace_array()
        print(f"Namespace Array: {namespace_array}")

        di_index = _find_namespace_index(namespace_array, "http://opcfoundation.org/UA/DI/")
        machinery_index = _find_namespace_index(namespace_array, "http://opcfoundation.org/UA/Machinery/")
        machinery_jobs_index = _find_namespace_index(namespace_array, "http://opcfoundation.org/UA/Machinery/Jobs/")
        if di_index is None or machinery_index is None or machinery_jobs_index is None:
            print("Required OPC UA namespace (DI or Machinery) is not provided by the server, cannot continue")
            return EXIT_CODE_ERROR
        print(f"Found OPC for DI namespace with index: {di_index}")
        print(f"Found OPC for Machinery namespace with index: {machinery_index}")
        print(f"Found OPC for Machinery Jobs namespace with index: {machinery_jobs_index}")

        # Normalize configured NodeId/ExpandedNodeId (including nsu=...) into a
        # concrete NodeId string with namespace index for this server session.
        machine_nodeid = make_nodeid_string(UA_MACHINE_INSTANCE_NODEID, namespace_array)
        machine_node: Node = client.get_node(machine_nodeid)
        machine_displayname = await machine_node.read_display_name()
        print(f"Found machine instance ({machine_nodeid}): {machine_displayname.Text}")

        identification = await _read_machine_identification(machine_node, di_index)
        print(f"Read machine identification properties: {identification}")
        await create_aas_for_identification(machine_displayname.Text, identification, basyx_client)
        print("Created/Updated AAS for machine identification", UA_MACHINE_INSTANCE_NODEID, identification)

        job_manager_node = await _find_job_management_node(machine_node, machinery_index, machinery_jobs_index)
        if job_manager_node is None:
            return EXIT_CODE_ERROR

        job_order_results_node: Node = await job_manager_node.get_child(f"{machinery_jobs_index}:JobOrderResults")
        print(f"Found OPC for Machinery JobOrderResults node: {await job_order_results_node.read_display_name()}")

        references = await job_order_results_node.get_references(refs=ua.ObjectIds.GeneratesEvent)
        print(f"Found {len(references)} GeneratesEvent references from Machinery JobOrderResults node")
        if len(references) == 0:
            print("No GeneratesEvent reference found for Machinery JobOrderResults node, cannot subscribe to events!")
            return EXIT_CODE_ERROR

        ref_des = references[0]
        event_type_nodeid = ref_des.NodeId.to_string()
        found_eventtype_node = client.get_node(event_type_nodeid)
        event_type_displayname: ua.LocalizedText = await found_eventtype_node.read_display_name()
        print(f"Using EventType-NodeId's: {event_type_displayname.Text} [{event_type_nodeid}] for subscription")

        subscription = await client.create_subscription(
            period=UA_PUBLISHING_INTERVAL, handler=handler, publishing=True
        )
        await subscription.subscribe_events(
            sourcenode=job_order_results_node, evtypes=[found_eventtype_node], where_clause_generation=True
        )
        await subscription.subscribe_data_change(
            client.get_node(ua.ObjectIds.Server_ServerStatus_CurrentTime),
            ua.AttributeIds.Value,
            1,
            ua.MonitoringMode.Reporting,
            5000,  # 5 second heartbeat-like data change to help detect stalled subscriptions/connections
        )

        exit_code = await _run_event_loop(
            handler, basyx_client, event_type_nodeid, event_type_displayname.Text, stop_event
        )
    except KeyboardInterrupt:
        print("Interrupted, shutting down...")
        exit_code = EXIT_CODE_INTERRUPTED
    except Exception as ex:  # pylint: disable=broad-except
        print(f"Error during OPC UA setup or event processing, stopping: {ex!r}")
        exit_code = EXIT_CODE_ERROR
    finally:
        await basyx_client.close()
        try:
            await client.disconnect()
        except Exception as ex:  # pylint: disable=broad-except
            print(f"Error while disconnecting the OPC UA client: {ex!r}")

    return exit_code


if __name__ == "__main__":
    try:
        sys.exit(asyncio.run(main()))
    except KeyboardInterrupt:
        print("Interrupted, shutting down...")
        sys.exit(EXIT_CODE_INTERRUPTED)
